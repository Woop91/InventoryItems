def draw_icon(img, x, y, name, scale=1, dim=1.0):
    rows = ICONS.get(name, ICONS["chat"])
    px = img.load()
    W, H = img.size
    for ry, row in enumerate(rows):
        for rx, c in enumerate(row):
            col = PALETTE.get(c)
            if not col:
                continue
            if dim != 1.0:
                col = tuple(int(v * dim) for v in col)
            for sy in range(scale):
                for sx in range(scale):
                    X, Y = x + rx * scale + sx, y + ry * scale + sy
                    if 0 <= X < W and 0 <= Y < H:
                        px[X, Y] = col
