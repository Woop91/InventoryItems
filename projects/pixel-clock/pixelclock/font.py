def _glyph(font, ch):
    g = font.get(ch)
    if g is None:
        g = font.get(ch.upper())
    if g is None:
        g = font.get("?")
    return g


def text_width(text, font=MED, scale=1, spacing=1):
    if not text:
        return 0
    w = sum(len(_glyph(font, c)[0]) for c in text) + spacing * (len(text) - 1)
    return w * scale


def draw_text(img, x, y, text, color, font=MED, scale=1, spacing=1, shadow=None):
    """Draw text onto a PIL RGB image at (x, y). Returns the x after the text."""
    px = img.load()
    W, H = img.size
    for ch in text:
        g = _glyph(font, ch)
        for ry, row in enumerate(g):
            for rx, c in enumerate(row):
                if c != "#":
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        X = x + rx * scale + sx
                        Y = y + ry * scale + sy
                        if shadow and 0 <= X + 1 < W and 0 <= Y + 1 < H:
                            if px[X + 1, Y + 1] == (0, 0, 0):
                                px[X + 1, Y + 1] = shadow
                        if 0 <= X < W and 0 <= Y < H:
                            px[X, Y] = color
        x += (len(g[0]) + spacing) * scale
    return x
